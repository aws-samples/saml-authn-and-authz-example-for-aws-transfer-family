import { Component, FileBase, IResolver, Project } from "projen";
import { Eslint, NodeProject } from "projen/lib/javascript";

// Custom projen component that switches a project from .eslintrc.json to an
// ESLint 9 flat config (eslint.config.mjs) built with typescript-eslint.
//
// projen 0.104 configures ESLint 9 but still writes the legacy .eslintrc.json
// and runs it with ESLINT_USE_FLAT_CONFIG=false; it has no flat config output.
// This component keeps projen's Eslint component as the single source of the
// rule set (projen's defaults plus anything added with addRules/addOverride/
// addIgnorePattern), and renders that same configuration as a flat config at
// synth time instead of the .eslintrc.json file.
//
// Create it after the project's eslint settings are final and before anything
// adds steps to the eslint task, because it resets that task.

const GENERATED_MARKER = "// ~~ Generated by projen. To modify, edit .projenrc.ts and run \"pnpm dlx projen\".";
const FLAT_CONFIG_FILE = "eslint.config.mjs";

/**
 * Converts an .eslintrc ignore/override pattern (gitignore semantics: a pattern
 * without a slash matches at any depth, and a pattern that matches a directory
 * covers everything below it) to flat config globs, which are always relative
 * to the config file and only match files unless they end in `/**`.
 */
function toFlatGlobs(pattern: string): string[] {
  const p = pattern.replace(/\/$/, "");
  const anchored = p.includes("/") ? p.replace(/^\//, "") : `**/${p}`;
  return [anchored, `${anchored}/**`];
}

class EslintFlatConfigFile extends FileBase {
  constructor(project: Project, private readonly eslint: Eslint) {
    super(project, FLAT_CONFIG_FILE, { readonly: true, marker: false });
  }

  protected synthesizeContent(resolver: IResolver): string | undefined {
    const config = resolver.resolve(this.eslint.config);
    const json = (value: unknown, indent: string) =>
      JSON.stringify(value, undefined, 2).replace(/\n/g, `\n${indent}`);

    const ignores = (config.ignorePatterns ?? []).flatMap(toFlatGlobs);
    const overrides = (config.overrides ?? []).map((o: { files: string[]; rules: unknown }) => [
      "  {",
      `    files: ${json(o.files.flatMap(toFlatGlobs), "    ")},`,
      `    rules: ${json(o.rules, "    ")},`,
      "  },"
    ].join("\n"));

    return [
      GENERATED_MARKER,
      "import stylistic from \"@stylistic/eslint-plugin\";",
      "import { defineConfig } from \"eslint/config\";",
      "import importPlugin from \"eslint-plugin-import\";",
      "import tseslint from \"typescript-eslint\";",
      "",
      "const files = [\"**/*.ts\", \"**/*.tsx\"];",
      "",
      "export default defineConfig(",
      `  { ignores: ${json(ignores, "  ")} },`,
      "  // Equivalent of the legacy \"plugin:import/typescript\" preset.",
      "  { ...importPlugin.flatConfigs.typescript, files },",
      "  {",
      "    files,",
      "    languageOptions: {",
      "      parser: tseslint.parser,",
      `      ecmaVersion: ${json(config.parserOptions.ecmaVersion, "      ")},`,
      `      sourceType: ${json(config.parserOptions.sourceType, "      ")},`,
      "      parserOptions: {",
      `        projectService: ${json(config.parserOptions.projectService, "        ")},`,
      "        tsconfigRootDir: import.meta.dirname,",
      "      },",
      "    },",
      "    plugins: {",
      "      \"@typescript-eslint\": tseslint.plugin,",
      "      \"@stylistic\": stylistic,",
      "    },",
      `    settings: ${json(config.settings, "    ")},`,
      `    rules: ${json(config.rules, "    ")},`,
      "  },",
      ...overrides,
      ");",
      ""
    ].join("\n");
  }
}

export class EslintFlatConfig extends Component {
  constructor(project: NodeProject) {
    super(project);

    const eslint = Eslint.of(project);
    if (!eslint) {
      throw new Error("EslintFlatConfig requires the project to have eslint enabled");
    }

    // Replace the legacy config file with the flat config.
    project.tryRemoveFile(".eslintrc.json");
    new EslintFlatConfigFile(project, eslint);
    project.npmignore?.exclude(`/${FLAT_CONFIG_FILE}`);

    // The typescript-eslint package bundles the parser and plugin for flat
    // config, so it replaces the two separate packages projen adds.
    project.deps.removeDependency("@typescript-eslint/eslint-plugin");
    project.deps.removeDependency("@typescript-eslint/parser");
    project.addDevDeps("typescript-eslint@^8");

    // Flat config selects files through `files` globs, so --ext is gone, and
    // ESLint 9 uses flat config by default once ESLINT_USE_FLAT_CONFIG=false
    // is no longer set.
    eslint.eslintTask.reset();
    eslint.eslintTask.execArgs(
      ["eslint", "--fix", "--no-error-on-unmatched-pattern", "$@", ...eslint.lintPatterns],
      { receiveArgs: true }
    );
    project.tryFindObjectFile(".projen/tasks.json")
      ?.addDeletionOverride("tasks.eslint.env.ESLINT_USE_FLAT_CONFIG");
  }
}
